#!/usr/bin/env bash
# ============================================================
# script-template.sh — заготовка для нового bash-скрипта.
# ============================================================
#
# КАК ПОЛЬЗОВАТЬСЯ:
#   1. Скопируй этот файл под новым именем: cp script-template.sh myscript.sh
#   2. Открой myscript.sh в редакторе и впиши свою логику
#   3. Сделай исполняемым: chmod +x myscript.sh
#   4. Запусти: ./myscript.sh
#
# ПРАВИЛА:
#   - Каждый скрипт начинается с #!/usr/bin/env bash
#   - set -euo pipefail — падать при первой ошибке, не терпеть
#     undefined переменные, не терпеть broken pipe
#   - Все комментарии на русском (или английском — как тебе удобно)
#   - echo — печатать пользователю
#   - return / exit — выходить с правильным кодом (0 = успех, 1+ = ошибка)
# ============================================================

set -euo pipefail

# --- Конфигурация (параметры по умолчанию) ---
DEFAULT_NAME="World"

# --- Парсинг аргументов командной строки ---
# Поддержка: --name VALUE, -h/--help, --quiet
QUIET=0
NAME="$DEFAULT_NAME"
while [[ $# -gt 0 ]]; do
  case "$1" in
    --name) NAME="$2"; shift 2 ;;
    -h|--help)
      # Печать help-текста из шапки файла
      sed -n '2,20p' "$0"
      exit 0
      ;;
    --quiet) QUIET=1; shift ;;
    *) echo "Неизвестный аргумент: $1" >&2; exit 2 ;;
  esac
done

# --- Проверка зависимостей ---
if ! command -v rg >/dev/null 2>&1; then
  echo "Ошибка: нужен ripgrep (rg). Установи: brew install ripgrep" >&2
  exit 2
fi

# --- Основная логика ---
log() {
  [ "$QUIET" -eq 1 ] && return
  echo "$@"
}

log "Привет, $NAME!"
log "Сегодня: $(date '+%Y-%m-%d %H:%M')"
log "Папка: $(pwd)"

# TODO: впиши свою логику здесь

log "Готово."
